BEGIN;

CREATE SEQUENCE IF NOT EXISTS service_request_reference_seq;

CREATE TABLE IF NOT EXISTS service_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no TEXT NOT NULL UNIQUE,
    request_type TEXT NOT NULL,
    title TEXT NOT NULL,
    form_data JSONB NOT NULL DEFAULT '{}'::JSONB,
    status TEXT NOT NULL DEFAULT 'Submitted',
    requested_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT service_requests_type_check CHECK (
        request_type IN ('BORROWING', 'FACILITY_USE', 'JOB_REQUEST', 'PURCHASE_REQUISITION', 'LOSS_DAMAGE_REPORT')
    ),
    CONSTRAINT service_requests_status_check CHECK (
        status IN (
            'Submitted', 'Under Review', 'Needs Information', 'Approved', 'Rejected',
            'Ready for Pickup', 'Issued', 'Return Requested', 'Returned', 'For Repair',
            'In Progress', 'Completed', 'Closed', 'Cancelled'
        )
    ),
    CONSTRAINT service_requests_reference_not_blank CHECK (length(trim(reference_no)) > 0),
    CONSTRAINT service_requests_title_not_blank CHECK (length(trim(title)) > 0)
);

CREATE INDEX IF NOT EXISTS service_requests_requester_created_idx
    ON service_requests (requested_by_user_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS service_requests_status_created_idx
    ON service_requests (status, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS service_requests_type_status_created_idx
    ON service_requests (request_type, status, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS service_request_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_requests(id) ON DELETE RESTRICT,
    item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL,
    unit_of_measure TEXT NOT NULL,
    condition_out TEXT,
    condition_in TEXT,
    due_date DATE,
    issued_at TIMESTAMPTZ,
    returned_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT service_request_assets_quantity_positive CHECK (quantity > 0),
    CONSTRAINT service_request_assets_unit_not_blank CHECK (length(trim(unit_of_measure)) > 0),
    CONSTRAINT service_request_assets_condition_out_check CHECK (
        condition_out IS NULL OR condition_out IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired')
    ),
    CONSTRAINT service_request_assets_condition_in_check CHECK (
        condition_in IS NULL OR condition_in IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired')
    )
);

CREATE INDEX IF NOT EXISTS service_request_assets_request_idx
    ON service_request_assets (request_id, id);
CREATE INDEX IF NOT EXISTS service_request_assets_item_idx
    ON service_request_assets (item_id, request_id);

CREATE TABLE IF NOT EXISTS service_request_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES service_requests(id) ON DELETE RESTRICT,
    previous_status TEXT,
    new_status TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT service_request_history_note_length CHECK (length(note) <= 2000)
);

CREATE INDEX IF NOT EXISTS service_request_history_request_changed_idx
    ON service_request_history (request_id, changed_at DESC, id DESC);

COMMIT;
