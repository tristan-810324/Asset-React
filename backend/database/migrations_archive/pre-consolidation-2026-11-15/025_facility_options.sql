-- Facility Use places: the venues a requester can pick. GSO adds, renames, hides, and shows them.
BEGIN;

CREATE TABLE facility_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_type TEXT NOT NULL,
    label TEXT NOT NULL,
    requires_detail BOOLEAN NOT NULL DEFAULT FALSE,
    detail_label TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT facility_options_type_check CHECK (option_type = 'VENUE'),
    CONSTRAINT facility_options_label_check CHECK (length(btrim(label)) BETWEEN 1 AND 120),
    CONSTRAINT facility_options_detail_check CHECK (
        requires_detail = FALSE OR length(btrim(COALESCE(detail_label, ''))) BETWEEN 1 AND 80
    )
);

CREATE UNIQUE INDEX facility_options_type_label_key
    ON facility_options (option_type, lower(btrim(label)));

