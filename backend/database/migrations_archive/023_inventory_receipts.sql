BEGIN;

CREATE TABLE IF NOT EXISTS inventory_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL,
    unit_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    date_acquired DATE,
    time_acquired TIME,
    reference_number TEXT NOT NULL DEFAULT '',
    recorded_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT inventory_receipts_quantity_positive CHECK (quantity > 0),
    CONSTRAINT inventory_receipts_costs_nonnegative CHECK (unit_cost >= 0 AND total_cost >= 0)
);

CREATE INDEX IF NOT EXISTS inventory_receipts_item_date_idx
    ON inventory_receipts (item_id, date_acquired DESC, id DESC);

INSERT INTO inventory_receipts (
    item_id, quantity, unit_cost, total_cost, date_acquired, time_acquired,
    reference_number, recorded_by_user_id, created_at
)
SELECT id, quantity, unit_cost, acquisition_cost, date_acquired, time_acquired,
       'Opening balance', created_by_user_id, created_at
  FROM item_catalog
 WHERE quantity > 0
   AND NOT EXISTS (
       SELECT 1
         FROM inventory_receipts AS existing_receipt
        WHERE existing_receipt.item_id = item_catalog.id
   );

COMMIT;
