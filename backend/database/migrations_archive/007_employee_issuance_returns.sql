BEGIN;

CREATE TABLE IF NOT EXISTS employee_issuance_returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuance_id BIGINT NOT NULL REFERENCES employee_issuances(id) ON DELETE RESTRICT,
    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    token_hash TEXT NOT NULL UNIQUE,
    token_expires_at TIMESTAMPTZ NOT NULL,
    return_condition TEXT NOT NULL,
    reason TEXT NOT NULL,
    decision_note TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    email_sent_at TIMESTAMPTZ,
    CONSTRAINT employee_issuance_returns_status_check
        CHECK (status IN ('Pending', 'Returned', 'Rejected', 'Expired', 'Email Failed')),
    CONSTRAINT employee_issuance_returns_condition_check
        CHECK (return_condition IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired')),
    CONSTRAINT employee_issuance_returns_reason_check
        CHECK (length(trim(reason)) BETWEEN 1 AND 1000)
);

CREATE INDEX IF NOT EXISTS employee_issuance_returns_issuance_requested_idx
    ON employee_issuance_returns (issuance_id, requested_at DESC, id DESC);
CREATE UNIQUE INDEX IF NOT EXISTS employee_issuance_returns_one_pending_idx
    ON employee_issuance_returns (issuance_id)
    WHERE status = 'Pending';

COMMIT;
