-- Completes the return flow: repair holds for bulk stock, lost units and their settlement,
-- corrections by IT Admin, overdue reminders, IT Admin override codes, and inventory counts.
BEGIN;

-- Bulk units set aside after a damaged return. They are not issued again until GSO marks
-- them repaired or written off. Tagged units keep this state on their own tag instead.
ALTER TABLE item_catalog
    ADD COLUMN IF NOT EXISTS repair_quantity INTEGER NOT NULL DEFAULT 0;
ALTER TABLE item_catalog
    DROP CONSTRAINT IF EXISTS item_catalog_repair_quantity_check;
ALTER TABLE item_catalog
    ADD CONSTRAINT item_catalog_repair_quantity_check CHECK (repair_quantity >= 0);

ALTER TABLE employee_issuance_returns
    DROP CONSTRAINT IF EXISTS employee_issuance_returns_status_check;
ALTER TABLE employee_issuance_returns
    ADD CONSTRAINT employee_issuance_returns_status_check
    CHECK (status IN ('Pending', 'Returned', 'Rejected', 'Expired', 'Email Failed', 'Lost', 'Voided'));

ALTER TABLE employee_issuance_returns
    DROP CONSTRAINT IF EXISTS employee_issuance_returns_condition_check;
ALTER TABLE employee_issuance_returns
    ADD CONSTRAINT employee_issuance_returns_condition_check
    CHECK (return_condition IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired', 'Lost'));

ALTER TABLE employee_issuance_returns
    ADD COLUMN IF NOT EXISTS returned_by_name TEXT,
    ADD COLUMN IF NOT EXISTS confirmation_method TEXT,
    ADD COLUMN IF NOT EXISTS tag_snapshot JSONB,
    ADD COLUMN IF NOT EXISTS repair_outcome TEXT,
    ADD COLUMN IF NOT EXISTS repair_resolved_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS repair_resolved_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS settlement_status TEXT,
    ADD COLUMN IF NOT EXISTS settlement_note TEXT,
    ADD COLUMN IF NOT EXISTS settled_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS settled_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS voided_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS voided_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS void_reason TEXT;

ALTER TABLE employee_issuance_returns
    DROP CONSTRAINT IF EXISTS employee_issuance_returns_completion_check;
ALTER TABLE employee_issuance_returns
    ADD CONSTRAINT employee_issuance_returns_completion_check CHECK (
        (returned_by_name IS NULL OR length(returned_by_name) <= 200)
        AND (confirmation_method IS NULL OR confirmation_method IN ('scan', 'typed_code', 'employee_code', 'admin_override'))
        AND (repair_outcome IS NULL OR repair_outcome IN ('Repaired', 'Written Off'))
        AND (settlement_status IS NULL OR settlement_status IN ('Pending', 'Replaced', 'Paid', 'Waived'))
        AND (status <> 'Lost' OR settlement_status IS NOT NULL)
    );

CREATE INDEX IF NOT EXISTS employee_issuance_returns_open_settlement_idx
    ON employee_issuance_returns (issuance_id)
    WHERE status = 'Lost' AND settlement_status = 'Pending';

-- Last overdue reminder sent for a reusable-stock borrowing, so reminders go out once a day.
ALTER TABLE employee_issuance_batches
    ADD COLUMN IF NOT EXISTS overdue_reminded_at TIMESTAMPTZ;

-- A code IT Admin creates and reads out when the employee cannot receive one by email.
ALTER TABLE asset_return_otps
    ADD COLUMN IF NOT EXISTS override_reason TEXT;

-- Blind stock counts: what was counted, what the records expected, and the differences.
CREATE TABLE IF NOT EXISTS inventory_counts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    counted_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    note TEXT NOT NULL DEFAULT '',
    lines JSONB NOT NULL,
    discrepancy_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT inventory_counts_note_length CHECK (length(note) <= 1000)
);

CREATE INDEX IF NOT EXISTS inventory_counts_created_idx
    ON inventory_counts (created_at DESC, id DESC);

COMMIT;
