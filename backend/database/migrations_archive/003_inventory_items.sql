BEGIN;

CREATE TABLE IF NOT EXISTS item_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    date_acquired DATE,
    time_acquired TIME,
    unit_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    acquisition_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    current_value NUMERIC(12, 2),
    quantity INTEGER NOT NULL DEFAULT 1,
    unit_of_measure TEXT NOT NULL DEFAULT 'piece',
    condition TEXT NOT NULL DEFAULT 'New',
    inventory_status TEXT NOT NULL DEFAULT 'Available',
    created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT item_catalog_code_not_blank CHECK (length(trim(item_code)) > 0),
    CONSTRAINT item_catalog_category_not_blank CHECK (length(trim(category)) > 0),
    CONSTRAINT item_catalog_description_not_blank CHECK (length(trim(description)) > 0),
    CONSTRAINT item_catalog_unit_not_blank CHECK (length(trim(unit_of_measure)) > 0),
    CONSTRAINT item_catalog_costs_nonnegative CHECK (
        unit_cost >= 0 AND acquisition_cost >= 0 AND (current_value IS NULL OR current_value >= 0)
    ),
    CONSTRAINT item_catalog_quantity_nonnegative CHECK (quantity >= 0),
    CONSTRAINT item_catalog_condition_check CHECK (
        condition IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired')
    ),
    CONSTRAINT item_catalog_status_check CHECK (
        inventory_status IN ('Available', 'Issued', 'Reserved', 'Borrowed')
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS item_catalog_code_lower_unique_idx
    ON item_catalog (lower(item_code));
CREATE INDEX IF NOT EXISTS item_catalog_created_at_idx
    ON item_catalog (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS item_catalog_category_condition_idx
    ON item_catalog (category, condition);

COMMIT;
