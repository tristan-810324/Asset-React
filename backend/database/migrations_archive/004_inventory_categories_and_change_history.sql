BEGIN;

CREATE TABLE IF NOT EXISTS item_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT item_categories_name_not_blank CHECK (length(trim(name)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS item_categories_name_lower_unique_idx
    ON item_categories (lower(name));

INSERT INTO item_categories (name)
VALUES
    ('Office Supplies'),
    ('Office Equipment'),
    ('Machinery/ Parts'),
    ('Computer Parts/ Peripherals'),
    ('Tools/ Equipment'),
    ('Publications'),
    ('Electrical Supplies'),
    ('Other Consumables'),
    ('Others')
ON CONFLICT (lower(name)) DO NOTHING;

-- Preserve custom categories already stored on inventory items (including older rows).
INSERT INTO item_categories (name)
SELECT DISTINCT trim(category)
  FROM item_catalog
 WHERE category IS NOT NULL
   AND length(trim(category)) > 0
ON CONFLICT (lower(name)) DO NOTHING;

ALTER TABLE item_catalog
    ADD COLUMN IF NOT EXISTS category_id BIGINT;

UPDATE item_catalog AS item
   SET category_id = category_row.id,
       category = category_row.name
  FROM item_categories AS category_row
 WHERE item.category_id IS NULL
   AND lower(trim(item.category)) = lower(category_row.name);

ALTER TABLE item_catalog
    ALTER COLUMN category_id SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
          FROM pg_constraint
         WHERE conname = 'item_catalog_category_id_fk'
           AND conrelid = 'item_catalog'::regclass
    ) THEN
        ALTER TABLE item_catalog
            ADD CONSTRAINT item_catalog_category_id_fk
            FOREIGN KEY (category_id) REFERENCES item_categories(id) ON DELETE RESTRICT;
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS item_catalog_category_id_condition_idx
    ON item_catalog (category_id, condition);

CREATE TABLE IF NOT EXISTS inventory_change_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type TEXT NOT NULL,
    entity_key TEXT NOT NULL,
    entity_name TEXT NOT NULL,
    item_id BIGINT REFERENCES item_catalog(id) ON DELETE SET NULL,
    category_id BIGINT REFERENCES item_categories(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    reason TEXT NOT NULL,
    old_values JSONB NOT NULL DEFAULT '{}'::JSONB,
    new_values JSONB NOT NULL DEFAULT '{}'::JSONB,
    changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT inventory_change_logs_entity_type_check CHECK (entity_type IN ('item', 'category')),
    CONSTRAINT inventory_change_logs_action_check CHECK (action IN ('created', 'updated', 'renamed', 'deleted')),
    CONSTRAINT inventory_change_logs_reason_not_blank CHECK (length(trim(reason)) > 0)
);

CREATE INDEX IF NOT EXISTS inventory_change_logs_item_changed_at_idx
    ON inventory_change_logs (item_id, changed_at DESC);
CREATE INDEX IF NOT EXISTS inventory_change_logs_category_changed_at_idx
    ON inventory_change_logs (category_id, changed_at DESC);
CREATE INDEX IF NOT EXISTS inventory_change_logs_changed_at_idx
    ON inventory_change_logs (changed_at DESC, id DESC);

COMMIT;
