-- A reprinted unit label gets a new barcode and the old one is retired, so a copy of an old or
-- lost label stops working. Every reprint records who printed it and why.
BEGIN;

ALTER TABLE asset_unit_tags
    ADD COLUMN IF NOT EXISTS label_version INTEGER NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS asset_label_reprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_unit_tag_id BIGINT NOT NULL REFERENCES asset_unit_tags(id) ON DELETE RESTRICT,
    old_tag_code TEXT NOT NULL,
    new_tag_code TEXT NOT NULL,
    label_version INTEGER NOT NULL,
    reason TEXT NOT NULL,
    printed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT asset_label_reprints_reason_check CHECK (length(btrim(reason)) BETWEEN 1 AND 500)
);

-- A retired code is never reused, and scanning it finds the reprint that replaced it.
CREATE UNIQUE INDEX IF NOT EXISTS asset_label_reprints_old_code_idx
    ON asset_label_reprints (old_tag_code);
CREATE INDEX IF NOT EXISTS asset_label_reprints_tag_idx
    ON asset_label_reprints (asset_unit_tag_id, created_at DESC, id DESC);

COMMIT;
