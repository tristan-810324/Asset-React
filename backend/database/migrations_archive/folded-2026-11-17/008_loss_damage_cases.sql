-- Loss & Damage Cases: GSO Staff record a decision and an auditable custody hand-off for each report.
-- The report itself stays in service_requests (request_type LOSS_DAMAGE_REPORT).
BEGIN;

-- One decision per report. RESOLVED is retained only for historical records migrated from the retired flow.
CREATE TABLE public.loss_damage_settlements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL,
    resolution text NOT NULL,
    reason text NOT NULL,
    status text NOT NULL,
    assessed_by_user_id bigint,
    assessed_at timestamp with time zone DEFAULT now() NOT NULL,
    custody_resolved_at timestamp with time zone,
    custody_resolved_by_user_id bigint,
    custody_resolution_summary text,
    legacy_settlement_metadata jsonb,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT loss_damage_settlements_request_key UNIQUE (request_id),
    CONSTRAINT loss_damage_settlements_resolution_check CHECK ((resolution = ANY (ARRAY['NO_CHARGE'::text, 'FOR_REPAIR'::text, 'RESOLVED'::text]))),
    CONSTRAINT loss_damage_settlements_status_check CHECK ((
        ((resolution = 'NO_CHARGE'::text) AND (status = 'NO_CHARGE'::text))
        OR ((resolution = 'FOR_REPAIR'::text) AND (status = 'FOR_REPAIR'::text))
        OR ((resolution = 'RESOLVED'::text) AND (status = 'RESOLVED'::text))
    )),
    CONSTRAINT loss_damage_settlements_reason_check CHECK (((length(btrim(reason)) >= 1) AND (length(reason) <= 1000))),
    CONSTRAINT loss_damage_settlements_custody_summary_check CHECK ((custody_resolution_summary IS NULL OR length(custody_resolution_summary) <= 2000)),
    CONSTRAINT loss_damage_settlements_request_id_fkey FOREIGN KEY (request_id) REFERENCES public.service_requests(id) ON DELETE RESTRICT,
    CONSTRAINT loss_damage_settlements_assessed_by_user_id_fkey FOREIGN KEY (assessed_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL,
    CONSTRAINT loss_damage_settlements_custody_resolved_by_user_id_fkey FOREIGN KEY (custody_resolved_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL
);

CREATE INDEX loss_damage_settlements_status_idx ON public.loss_damage_settlements USING btree (status, request_id);

COMMIT;
