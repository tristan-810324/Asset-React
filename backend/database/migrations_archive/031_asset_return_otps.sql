-- One-time codes the borrower reads out at the GSO counter to confirm a return whose
-- barcode was typed instead of scanned. Kept apart from employee_issuance_returns, whose
-- token hashes are looked up by the public return-approval link.
BEGIN;

CREATE TABLE IF NOT EXISTS asset_return_otps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_unit_tag_id BIGINT NOT NULL REFERENCES asset_unit_tags(id) ON DELETE RESTRICT,
    issuance_id BIGINT NOT NULL REFERENCES employee_issuances(id) ON DELETE RESTRICT,
    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    token_hash TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT asset_return_otps_attempts_range CHECK (attempts BETWEEN 0 AND 5)
);

CREATE INDEX IF NOT EXISTS asset_return_otps_open_tag_idx
    ON asset_return_otps (asset_unit_tag_id)
    WHERE used_at IS NULL;

COMMIT;
