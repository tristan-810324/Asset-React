-- The audit log shown in Audit Logs: every change to items, categories, and employees,
-- including issuance and return events, with the values before and after.
BEGIN;

CREATE TABLE inventory_change_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type TEXT NOT NULL,
    entity_key TEXT NOT NULL,
    entity_name TEXT NOT NULL,
    item_id BIGINT REFERENCES item_catalog(id) ON DELETE SET NULL,
    category_id BIGINT REFERENCES item_categories(id) ON DELETE SET NULL,
    employee_id BIGINT REFERENCES employees(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    reason TEXT NOT NULL,
    old_values JSONB NOT NULL DEFAULT '{}'::JSONB,
    new_values JSONB NOT NULL DEFAULT '{}'::JSONB,
    changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT inventory_change_logs_entity_type_check CHECK (entity_type IN ('item', 'category', 'employee')),
    CONSTRAINT inventory_change_logs_action_check CHECK (action IN ('created', 'updated', 'renamed', 'deleted')),
    CONSTRAINT inventory_change_logs_reason_not_blank CHECK (length(trim(reason)) > 0)
);

CREATE INDEX inventory_change_logs_item_changed_at_idx ON inventory_change_logs (item_id, changed_at DESC);
CREATE INDEX inventory_change_logs_category_changed_at_idx ON inventory_change_logs (category_id, changed_at DESC);
CREATE INDEX inventory_change_logs_employee_changed_at_idx ON inventory_change_logs (employee_id, changed_at DESC);
CREATE INDEX inventory_change_logs_changed_at_idx ON inventory_change_logs (changed_at DESC, id DESC);

COMMIT;
