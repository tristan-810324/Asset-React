-- Returning issued items: partial and lost returns, repair holds, settlements, IT Admin
-- approvals, and the one-time codes employees give at the GSO counter.
BEGIN;

CREATE TABLE employee_issuance_returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuance_id BIGINT NOT NULL REFERENCES employee_issuances(id) ON DELETE RESTRICT,
    asset_unit_tag_id BIGINT REFERENCES asset_unit_tags(id) ON DELETE RESTRICT,
    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    token_hash TEXT NOT NULL UNIQUE,
    token_expires_at TIMESTAMPTZ NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    return_condition TEXT NOT NULL,
    reason TEXT NOT NULL,
    decision_note TEXT,
    returned_by_name TEXT,
    confirmation_method TEXT,
    tag_snapshot JSONB, -- the unit's barcode and details at return time, kept after the barcode retires
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    email_sent_at TIMESTAMPTZ,
    -- Damaged bulk units: put back in stock or written off.
    repair_outcome TEXT,
    repair_resolved_at TIMESTAMPTZ,
    repair_resolved_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    -- Lost units: how the loss was settled.
    settlement_status TEXT,
    settlement_note TEXT,
    settled_at TIMESTAMPTZ,
    settled_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    -- GSO asks and IT Admin decides a write-off or a paid or replaced settlement.
    approval_action TEXT,
    approval_note TEXT,
    approval_requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    approval_requested_at TIMESTAMPTZ,
    approval_decision_note TEXT,
    -- Voided returns, from the removed IT Admin correction feature, still show in records.
    voided_at TIMESTAMPTZ,
    voided_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    void_reason TEXT,
    CONSTRAINT employee_issuance_returns_status_check
        CHECK (status IN ('Pending', 'Returned', 'Rejected', 'Expired', 'Email Failed', 'Lost', 'Voided')),
    CONSTRAINT employee_issuance_returns_condition_check CHECK (
        return_condition IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired', 'Lost')
    ),
    CONSTRAINT employee_issuance_returns_reason_check CHECK (length(trim(reason)) BETWEEN 1 AND 1000),
    CONSTRAINT employee_issuance_returns_quantity_positive_check CHECK (quantity > 0),
    CONSTRAINT employee_issuance_returns_completion_check CHECK (
        (returned_by_name IS NULL OR length(returned_by_name) <= 200)
        AND (confirmation_method IS NULL OR confirmation_method IN ('scan', 'typed_code', 'employee_code', 'admin_override'))
        AND (repair_outcome IS NULL OR repair_outcome IN ('Repaired', 'Written Off'))
        AND (settlement_status IS NULL OR settlement_status IN ('Pending', 'Replaced', 'Paid', 'Waived'))
        AND (status <> 'Lost' OR settlement_status IS NOT NULL)
    ),
    CONSTRAINT employee_issuance_returns_approval_check CHECK (
        (approval_action IS NULL OR approval_action IN ('Written Off', 'Paid', 'Replaced'))
        AND (approval_note IS NULL OR length(approval_note) <= 1000)
        AND (approval_decision_note IS NULL OR length(approval_decision_note) <= 1000)
    )
);

CREATE INDEX employee_issuance_returns_issuance_requested_idx
    ON employee_issuance_returns (issuance_id, requested_at DESC, id DESC);
CREATE UNIQUE INDEX employee_issuance_returns_one_pending_idx
    ON employee_issuance_returns (issuance_id)
    WHERE status = 'Pending';
CREATE INDEX employee_issuance_returns_asset_unit_tag_idx
    ON employee_issuance_returns (asset_unit_tag_id, decided_at DESC)
    WHERE asset_unit_tag_id IS NOT NULL;
CREATE INDEX employee_issuance_returns_open_settlement_idx
    ON employee_issuance_returns (issuance_id)
    WHERE status = 'Lost' AND settlement_status = 'Pending';
CREATE INDEX employee_issuance_returns_approval_idx
    ON employee_issuance_returns (approval_requested_at)
    WHERE approval_action IS NOT NULL;

-- One-time codes the employee reads out at the GSO counter to confirm a return. A unit code
-- names its barcode; a bulk code is bound to the quantity and condition the employee was shown.
-- Kept apart from employee_issuance_returns, whose token hashes the public approval link looks up.
CREATE TABLE asset_return_otps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_unit_tag_id BIGINT REFERENCES asset_unit_tags(id) ON DELETE RESTRICT,
    issuance_id BIGINT NOT NULL REFERENCES employee_issuances(id) ON DELETE RESTRICT,
    quantity INTEGER,
    return_condition TEXT,
    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    token_hash TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    override_reason TEXT, -- set only on IT Admin override codes from the removed override feature
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT asset_return_otps_attempts_range CHECK (attempts BETWEEN 0 AND 5),
    CONSTRAINT asset_return_otps_target_check CHECK (
        asset_unit_tag_id IS NOT NULL
        OR (quantity IS NOT NULL AND quantity > 0 AND return_condition IS NOT NULL)
    )
);

CREATE INDEX asset_return_otps_open_tag_idx
    ON asset_return_otps (asset_unit_tag_id)
    WHERE used_at IS NULL;
CREATE INDEX asset_return_otps_open_bulk_idx
    ON asset_return_otps (issuance_id)
    WHERE used_at IS NULL AND asset_unit_tag_id IS NULL;

COMMIT;
