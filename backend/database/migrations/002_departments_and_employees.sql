-- Departments and the employee master list that items are issued to.
BEGIN;

CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT departments_name_not_blank CHECK (length(trim(name)) > 0)
);

CREATE UNIQUE INDEX departments_name_lower_unique_idx ON departments (lower(name));

INSERT INTO departments (name)
VALUES
    ('Registrar Office'),
    ('IT Services'),
    ('Science Department'),
    ('Finance Office'),
    ('Property & Supply'),
    ('Academic Affairs'),
    ('Human Resources');

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code TEXT NOT NULL,
    first_name TEXT NOT NULL,
    middle_name TEXT NOT NULL DEFAULT '',
    last_name TEXT NOT NULL,
    suffix TEXT NOT NULL DEFAULT '',
    department TEXT NOT NULL,
    position TEXT NOT NULL,
    email TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Active',
    picture_data TEXT,
    created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT employees_code_not_blank CHECK (length(trim(employee_code)) > 0),
    CONSTRAINT employees_department_not_blank CHECK (length(trim(department)) > 0),
    CONSTRAINT employees_last_name_not_blank CHECK (length(trim(last_name)) > 0),
    CONSTRAINT employees_first_name_not_blank CHECK (length(trim(first_name)) > 0),
    CONSTRAINT employees_position_not_blank CHECK (length(trim(position)) > 0),
    CONSTRAINT employees_email_not_blank CHECK (length(trim(email)) > 0),
    CONSTRAINT employees_status_check CHECK (status IN ('Active', 'Inactive'))
);

CREATE UNIQUE INDEX employees_employee_code_lower_unique_idx ON employees (lower(employee_code));
CREATE UNIQUE INDEX employees_email_lower_unique_idx ON employees (lower(email));

COMMIT;
