BEGIN;

CREATE TABLE IF NOT EXISTS employee_issuance_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    token_hash TEXT NOT NULL UNIQUE,
    token_expires_at TIMESTAMPTZ NOT NULL,
    decision_note TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    email_sent_at TIMESTAMPTZ,
    CONSTRAINT employee_issuance_batches_status_check
        CHECK (status IN ('Pending', 'Issued', 'Rejected', 'Expired', 'Email Failed'))
);

ALTER TABLE employee_issuances
    ADD COLUMN IF NOT EXISTS batch_id BIGINT REFERENCES employee_issuance_batches(id) ON DELETE RESTRICT;

ALTER TABLE employee_issuances
    ALTER COLUMN token_hash DROP NOT NULL;

CREATE INDEX IF NOT EXISTS employee_issuance_batches_employee_requested_idx
    ON employee_issuance_batches (employee_id, requested_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS employee_issuance_batches_pending_expiry_idx
    ON employee_issuance_batches (token_expires_at, id)
    WHERE status = 'Pending';
CREATE INDEX IF NOT EXISTS employee_issuances_batch_idx
    ON employee_issuances (batch_id, id)
    WHERE batch_id IS NOT NULL;

COMMIT;
