-- Issuing stock to employees. A batch is one request the employee or verified requester
-- decides on; each employee_issuances row is one item in it. Reusable stock that is borrowed
-- also records when and where it is used and when it is due back.
BEGIN;

CREATE TABLE employee_issuance_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    requester_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT, -- verified requester account that decides
    status TEXT NOT NULL DEFAULT 'Pending',
    token_hash TEXT NOT NULL UNIQUE,
    token_expires_at TIMESTAMPTZ NOT NULL,
    decision_note TEXT,
    borrow_use_date DATE,
    expected_return_date DATE,
    borrow_use_at TIMESTAMPTZ,
    expected_return_at TIMESTAMPTZ,
    use_location TEXT,
    use_purpose TEXT,
    overdue_reminded_at TIMESTAMPTZ, -- last overdue reminder, so reminders go out once a day
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    email_sent_at TIMESTAMPTZ,
    CONSTRAINT employee_issuance_batches_status_check
        CHECK (status IN ('Pending', 'Issued', 'Rejected', 'Expired', 'Email Failed')),
    CONSTRAINT employee_issuance_batches_borrow_details_check CHECK (
        (borrow_use_date IS NULL AND expected_return_date IS NULL AND use_location IS NULL AND use_purpose IS NULL)
        OR (
            borrow_use_date IS NOT NULL
            AND expected_return_date IS NOT NULL
            AND expected_return_date >= borrow_use_date
            AND NULLIF(BTRIM(use_location), '') IS NOT NULL
            AND NULLIF(BTRIM(use_purpose), '') IS NOT NULL
        )
    ),
    CONSTRAINT employee_issuance_batches_borrow_time_check CHECK (
        (borrow_use_at IS NULL AND expected_return_at IS NULL)
        OR (
            borrow_use_at IS NOT NULL
            AND expected_return_at IS NOT NULL
            AND expected_return_at > borrow_use_at
        )
    )
);

CREATE INDEX employee_issuance_batches_employee_requested_idx
    ON employee_issuance_batches (employee_id, requested_at DESC, id DESC);
CREATE INDEX employee_issuance_batches_pending_expiry_idx
    ON employee_issuance_batches (token_expires_at, id)
    WHERE status = 'Pending';
CREATE INDEX employee_issuance_batches_requester_status_idx
    ON employee_issuance_batches (requester_user_id, status, requested_at DESC)
    WHERE requester_user_id IS NOT NULL;

CREATE TABLE employee_issuances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT REFERENCES employee_issuance_batches(id) ON DELETE RESTRICT,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    token_hash TEXT UNIQUE, -- only for single issuances made without a batch
    token_expires_at TIMESTAMPTZ NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    returned_quantity INTEGER NOT NULL DEFAULT 0,
    unit_of_measure TEXT NOT NULL DEFAULT 'piece',
    item_condition TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    decision_note TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    email_sent_at TIMESTAMPTZ,
    CONSTRAINT employee_issuances_status_check
        CHECK (status IN ('Pending', 'Issued', 'Rejected', 'Expired', 'Email Failed', 'Returned')),
    CONSTRAINT employee_issuances_notes_check CHECK (length(trim(notes)) <= 1000),
    CONSTRAINT employee_issuances_quantity_positive_check CHECK (quantity > 0),
    CONSTRAINT employee_issuances_returned_quantity_check
        CHECK (returned_quantity >= 0 AND returned_quantity <= quantity)
);

CREATE INDEX employee_issuances_employee_requested_idx
    ON employee_issuances (employee_id, requested_at DESC, id DESC);
CREATE INDEX employee_issuances_item_status_idx ON employee_issuances (item_id, status);
CREATE INDEX employee_issuances_batch_idx
    ON employee_issuances (batch_id, id)
    WHERE batch_id IS NOT NULL;

COMMIT;
