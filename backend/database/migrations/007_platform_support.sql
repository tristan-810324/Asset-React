CREATE TABLE public.app_notifications (
    id bigint NOT NULL,
    recipient_user_id bigint,
    recipient_role_key text,
    notification_type text NOT NULL,
    title text NOT NULL,
    message text NOT NULL,
    href text DEFAULT ''::text NOT NULL,
    dedupe_key text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    read_at timestamp with time zone,
    resolved_at timestamp with time zone,
    CONSTRAINT app_notifications_recipient_check CHECK (((recipient_user_id IS NULL) <> (recipient_role_key IS NULL)))
);

CREATE TABLE public.facility_options (
    id bigint NOT NULL,
    option_type text NOT NULL,
    label text NOT NULL,
    requires_detail boolean DEFAULT false NOT NULL,
    detail_label text,
    is_active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT facility_options_detail_check CHECK (((requires_detail = false) OR ((length(btrim(COALESCE(detail_label, ''::text))) >= 1) AND (length(btrim(COALESCE(detail_label, ''::text))) <= 80)))),
    CONSTRAINT facility_options_label_check CHECK (((length(btrim(label)) >= 1) AND (length(btrim(label)) <= 120))),
    CONSTRAINT facility_options_type_check CHECK ((option_type = 'VENUE'::text))
);

CREATE TABLE public.user_signatures (
    user_id bigint NOT NULL,
    image bytea NOT NULL,
    width integer NOT NULL,
    height integer NOT NULL,
    image_sha256 text NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_signatures_dimensions CHECK (((width > 0) AND (height > 0))),
    CONSTRAINT user_signatures_image_size CHECK ((octet_length(image) <= 307200))
);

