-- Notifications, GSO Head signatures, and Facility Use venue choices.
-- Consolidated from the pre-consolidation migrations (archived in migrations_archive/pre-consolidation-2026-11-15).
-- Reference data is included. One-time data conversions are not, because a new database has no rows to convert.
BEGIN;

CREATE TABLE public.app_notifications (
    id bigint NOT NULL,
    recipient_user_id bigint,
    recipient_role_key text,
    notification_type text NOT NULL,
    title text NOT NULL,
    message text NOT NULL,
    href text DEFAULT ''::text NOT NULL,
    dedupe_key text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    read_at timestamp with time zone,
    resolved_at timestamp with time zone,
    CONSTRAINT app_notifications_recipient_check CHECK (((recipient_user_id IS NULL) <> (recipient_role_key IS NULL)))
);

CREATE TABLE public.facility_options (
    id bigint NOT NULL,
    option_type text NOT NULL,
    label text NOT NULL,
    requires_detail boolean DEFAULT false NOT NULL,
    detail_label text,
    is_active boolean DEFAULT true NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT facility_options_detail_check CHECK (((requires_detail = false) OR ((length(btrim(COALESCE(detail_label, ''::text))) >= 1) AND (length(btrim(COALESCE(detail_label, ''::text))) <= 80)))),
    CONSTRAINT facility_options_label_check CHECK (((length(btrim(label)) >= 1) AND (length(btrim(label)) <= 120))),
    CONSTRAINT facility_options_type_check CHECK ((option_type = 'VENUE'::text))
);

CREATE TABLE public.user_signatures (
    user_id bigint NOT NULL,
    image bytea NOT NULL,
    width integer NOT NULL,
    height integer NOT NULL,
    image_sha256 text NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT user_signatures_dimensions CHECK (((width > 0) AND (height > 0))),
    CONSTRAINT user_signatures_image_size CHECK ((octet_length(image) <= 307200))
);

ALTER TABLE public.app_notifications ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.app_notifications_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE public.facility_options ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.facility_options_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.app_notifications
    ADD CONSTRAINT app_notifications_dedupe_key_key UNIQUE (dedupe_key);

ALTER TABLE ONLY public.app_notifications
    ADD CONSTRAINT app_notifications_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.facility_options
    ADD CONSTRAINT facility_options_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.user_signatures
    ADD CONSTRAINT user_signatures_pkey PRIMARY KEY (user_id);

CREATE INDEX app_notifications_role_inbox_idx ON public.app_notifications USING btree (recipient_role_key, created_at DESC) WHERE (resolved_at IS NULL);

CREATE INDEX app_notifications_user_inbox_idx ON public.app_notifications USING btree (recipient_user_id, created_at DESC) WHERE (resolved_at IS NULL);

CREATE UNIQUE INDEX facility_options_type_label_key ON public.facility_options USING btree (option_type, lower(btrim(label)));

ALTER TABLE ONLY public.app_notifications
    ADD CONSTRAINT app_notifications_recipient_user_id_fkey FOREIGN KEY (recipient_user_id) REFERENCES public.users(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.user_signatures
    ADD CONSTRAINT user_signatures_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

