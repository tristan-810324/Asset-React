-- Purchase requisitions: line routing, stock reservations, deliveries, and the saved item approval policy history.
-- Consolidated from the pre-consolidation migrations (archived in migrations_archive/pre-consolidation-2026-11-15).
-- Reference data is included. One-time data conversions are not, because a new database has no rows to convert.
BEGIN;

CREATE TABLE public.item_category_item_name_policy_history (
    id bigint NOT NULL,
    item_name_id bigint NOT NULL,
    previous_policy text NOT NULL,
    new_policy text NOT NULL,
    previous_staff_limit integer,
    new_staff_limit integer,
    reason text NOT NULL,
    changed_by_user_id bigint,
    changed_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT item_category_item_name_policy_history_reason_check CHECK (((length(TRIM(BOTH FROM reason)) >= 1) AND (length(TRIM(BOTH FROM reason)) <= 1000)))
);

CREATE TABLE public.purchase_requisition_line_allocations (
    id bigint NOT NULL,
    line_id bigint NOT NULL,
    item_id bigint NOT NULL,
    quantity integer NOT NULL,
    fulfilled_quantity integer DEFAULT 0 CONSTRAINT purchase_requisition_line_allocatio_fulfilled_quantity_not_null NOT NULL,
    status text DEFAULT 'Reserved'::text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT purchase_requisition_line_allocations_quantity_check CHECK (((quantity > 0) AND (fulfilled_quantity >= 0) AND (fulfilled_quantity <= quantity))),
    CONSTRAINT purchase_requisition_line_allocations_status_check CHECK ((status = ANY (ARRAY['Reserved'::text, 'Fulfilled'::text, 'Released'::text])))
);

CREATE TABLE public.purchase_requisition_line_receipts (
    id bigint NOT NULL,
    line_id bigint NOT NULL,
    item_id bigint NOT NULL,
    quantity integer NOT NULL,
    receipt_reference text DEFAULT ''::text NOT NULL,
    received_by_user_id bigint,
    received_at timestamp with time zone DEFAULT now() NOT NULL,
    voided_at timestamp with time zone,
    voided_by_user_id bigint,
    CONSTRAINT purchase_requisition_line_receipts_quantity_check CHECK ((quantity > 0))
);

CREATE TABLE public.purchase_requisition_lines (
    id bigint NOT NULL,
    request_id bigint NOT NULL,
    line_number integer NOT NULL,
    item_name_id bigint,
    category text NOT NULL,
    item_name text NOT NULL,
    specifications text DEFAULT ''::text NOT NULL,
    requested_quantity integer NOT NULL,
    approval_policy text DEFAULT 'GSO_HEAD'::text NOT NULL,
    staff_issue_max_quantity integer,
    reserved_quantity integer DEFAULT 0 NOT NULL,
    finance_quantity integer DEFAULT 0 NOT NULL,
    issued_quantity integer DEFAULT 0 NOT NULL,
    route_status text DEFAULT 'WAITING_STAFF_REVIEW'::text NOT NULL,
    review_note text DEFAULT ''::text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT purchase_requisition_lines_policy_check CHECK ((approval_policy = ANY (ARRAY['GSO_HEAD'::text, 'STAFF_ISSUE'::text]))),
    CONSTRAINT purchase_requisition_lines_quantity_check CHECK (((requested_quantity > 0) AND (reserved_quantity >= 0) AND (finance_quantity >= 0) AND (issued_quantity >= 0) AND ((reserved_quantity + finance_quantity) <= requested_quantity) AND (issued_quantity <= reserved_quantity))),
    CONSTRAINT purchase_requisition_lines_status_check CHECK ((route_status = ANY (ARRAY['WAITING_STAFF_REVIEW'::text, 'WAITING_GSO_HEAD'::text, 'NEEDS_INFORMATION'::text, 'READY_FOR_STAFF'::text, 'PARTIAL_STOCK'::text, 'WAITING_FINANCE'::text, 'WAITING_FOR_PURCHASE'::text, 'REJECTED'::text, 'PARTIALLY_ISSUED'::text, 'HANDOVER_PENDING'::text, 'ISSUED'::text, 'CANCELLED'::text])))
);

ALTER TABLE public.item_category_item_name_policy_history ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
