    ADD CONSTRAINT purchase_requisition_line_allocations_line_item_unique UNIQUE (line_id, item_id);

ALTER TABLE ONLY public.purchase_requisition_line_allocations
    ADD CONSTRAINT purchase_requisition_line_allocations_pkey PRIMARY KEY (id);

