    ADD CONSTRAINT purchase_requisition_lines_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.purchase_requisition_lines
    ADD CONSTRAINT purchase_requisition_lines_request_line_unique UNIQUE (request_id, line_number);

CREATE INDEX item_category_item_name_policy_history_item_idx ON public.item_category_item_name_policy_history USING btree (item_name_id, changed_at DESC, id DESC);

CREATE INDEX purchase_requisition_allocations_item_active_idx ON public.purchase_requisition_line_allocations USING btree (item_id, status) WHERE (status = 'Reserved'::text);

CREATE INDEX purchase_requisition_line_receipts_line_idx ON public.purchase_requisition_line_receipts USING btree (line_id, received_at DESC, id DESC);

CREATE INDEX purchase_requisition_lines_route_idx ON public.purchase_requisition_lines USING btree (route_status, request_id, line_number);

