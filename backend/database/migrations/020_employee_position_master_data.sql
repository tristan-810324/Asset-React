-- Managed employee positions. Employee, requester identity, and user records keep a
-- readable position name, while this table supplies the approved master-data choices.
BEGIN;

CREATE TABLE employee_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT employee_positions_name_not_blank CHECK (length(trim(name)) > 0)
);

CREATE UNIQUE INDEX employee_positions_name_lower_unique_idx
    ON employee_positions (lower(name));

-- Keep all established position labels available immediately after upgrading. The
-- sources are intentionally textual because those existing records predate this master list.
INSERT INTO employee_positions (name)
SELECT DISTINCT position
  FROM (
    SELECT trim(position) AS position
      FROM employees
     WHERE length(trim(position)) > 0
    UNION
    SELECT trim(position) AS position
      FROM requester_identity_profiles
     WHERE length(trim(position)) > 0
    UNION
    SELECT trim(position) AS position
      FROM users
     WHERE length(trim(position)) > 0
  ) AS existing_positions
ON CONFLICT DO NOTHING;

COMMIT;
