-- Keep employee issuance requests, decisions, and asset assignments in one place.
-- The email token is stored as a one-way hash and expires after the request window.
CREATE TABLE IF NOT EXISTS employee_issuances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
    requested_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    token_hash TEXT NOT NULL UNIQUE,
    token_expires_at TIMESTAMPTZ NOT NULL,
    item_condition TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    decision_note TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    email_sent_at TIMESTAMPTZ,
    CONSTRAINT employee_issuances_status_check
        CHECK (status IN ('Pending', 'Issued', 'Rejected', 'Expired', 'Email Failed', 'Returned')),
    CONSTRAINT employee_issuances_notes_check
        CHECK (length(trim(notes)) <= 1000)
);

CREATE INDEX IF NOT EXISTS employee_issuances_employee_requested_idx
    ON employee_issuances (employee_id, requested_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS employee_issuances_item_status_idx
    ON employee_issuances (item_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS employee_issuances_one_active_item_idx
    ON employee_issuances (item_id)
    WHERE status IN ('Pending', 'Issued');

