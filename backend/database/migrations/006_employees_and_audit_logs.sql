CREATE TABLE IF NOT EXISTS employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code TEXT NOT NULL,
    department TEXT NOT NULL,
    last_name TEXT NOT NULL,
    first_name TEXT NOT NULL,
    position TEXT NOT NULL,
    email TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Active',
    created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT employees_code_not_blank CHECK (length(trim(employee_code)) > 0),
    CONSTRAINT employees_department_not_blank CHECK (length(trim(department)) > 0),
    CONSTRAINT employees_last_name_not_blank CHECK (length(trim(last_name)) > 0),
    CONSTRAINT employees_first_name_not_blank CHECK (length(trim(first_name)) > 0),
    CONSTRAINT employees_position_not_blank CHECK (length(trim(position)) > 0),
    CONSTRAINT employees_email_not_blank CHECK (length(trim(email)) > 0),
    CONSTRAINT employees_status_check CHECK (status IN ('Active', 'Inactive'))
);

CREATE UNIQUE INDEX IF NOT EXISTS employees_employee_code_lower_unique_idx
    ON employees (lower(employee_code));
CREATE UNIQUE INDEX IF NOT EXISTS employees_email_lower_unique_idx
    ON employees (lower(email));

-- Preserve any department values already stored on employee profiles.
INSERT INTO departments (name)
SELECT DISTINCT trim(employee.department)   
  FROM employees AS employee
 WHERE employee.department IS NOT NULL
   AND length(trim(employee.department)) > 0
ON CONFLICT DO NOTHING;

