-- One stock record. "individual" stock gets one asset_unit_tags row per physical unit;
-- "quantity" stock is counted. Consumable stock is never returned.
CREATE TABLE item_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code TEXT NOT NULL,
    item_name TEXT NOT NULL,
    description TEXT NOT NULL,
    category_id BIGINT NOT NULL CONSTRAINT item_catalog_category_id_fk REFERENCES item_categories(id) ON DELETE RESTRICT,
    category TEXT NOT NULL, -- the category name, saved with the item
    serial_number TEXT,
    tracking_mode TEXT NOT NULL DEFAULT 'individual',
    issue_behavior TEXT NOT NULL DEFAULT 'returnable',
    quantity INTEGER NOT NULL DEFAULT 1,
    repair_quantity INTEGER NOT NULL DEFAULT 0, -- bulk units held for repair, not issuable
    unit_of_measure TEXT NOT NULL DEFAULT 'piece',
    condition TEXT NOT NULL DEFAULT 'New',
    inventory_status TEXT NOT NULL DEFAULT 'Available',
    location TEXT NOT NULL DEFAULT 'GSO Storage',
    date_acquired DATE,
    time_acquired TIME,
    unit_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    acquisition_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    current_value NUMERIC(12, 2),
    created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT item_catalog_code_not_blank CHECK (length(trim(item_code)) > 0),
    CONSTRAINT item_catalog_item_name_not_blank CHECK (length(trim(item_name)) > 0),
    CONSTRAINT item_catalog_category_not_blank CHECK (length(trim(category)) > 0),
    CONSTRAINT item_catalog_description_not_blank CHECK (length(trim(description)) > 0),
    CONSTRAINT item_catalog_unit_not_blank CHECK (length(trim(unit_of_measure)) > 0),
    CONSTRAINT item_catalog_costs_nonnegative CHECK (
        unit_cost >= 0 AND acquisition_cost >= 0 AND (current_value IS NULL OR current_value >= 0)
    ),
    CONSTRAINT item_catalog_quantity_nonnegative CHECK (quantity >= 0),
    CONSTRAINT item_catalog_repair_quantity_check CHECK (repair_quantity >= 0),
    CONSTRAINT item_catalog_condition_check CHECK (
        condition IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired')
    ),
    CONSTRAINT item_catalog_status_check CHECK (
        inventory_status IN ('Available', 'Issued', 'Reserved', 'Borrowed')
    ),
    CONSTRAINT item_catalog_tracking_mode_check CHECK (tracking_mode IN ('individual', 'quantity')),
    CONSTRAINT item_catalog_issue_behavior_check CHECK (issue_behavior IN ('consumable', 'returnable'))
);

CREATE UNIQUE INDEX item_catalog_code_lower_unique_idx ON item_catalog (lower(item_code));
CREATE UNIQUE INDEX item_catalog_serial_number_lower_unique_idx
    ON item_catalog (lower(btrim(serial_number)))
    WHERE serial_number IS NOT NULL AND btrim(serial_number) <> '';
CREATE INDEX item_catalog_created_at_idx ON item_catalog (created_at DESC, id DESC);
CREATE INDEX item_catalog_category_condition_idx ON item_catalog (category, condition);
CREATE INDEX item_catalog_category_id_condition_idx ON item_catalog (category_id, condition);
CREATE INDEX item_catalog_tracking_mode_idx ON item_catalog (tracking_mode, created_at DESC);
CREATE INDEX item_catalog_issue_behavior_idx ON item_catalog (tracking_mode, issue_behavior, created_at DESC);

-- Each delivery of stock: the opening balance and every later restock.
CREATE TABLE inventory_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL,
    unit_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_cost NUMERIC(12, 2) NOT NULL DEFAULT 0,
    date_acquired DATE,
    time_acquired TIME,
    reference_number TEXT NOT NULL DEFAULT '',
    recorded_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT inventory_receipts_quantity_positive CHECK (quantity > 0),
    CONSTRAINT inventory_receipts_costs_nonnegative CHECK (unit_cost >= 0 AND total_cost >= 0)
);

CREATE INDEX inventory_receipts_item_date_idx ON inventory_receipts (item_id, date_acquired DESC, id DESC);

-- Blind stock counts: what was counted, what the records expected, and the differences.
CREATE TABLE inventory_counts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    counted_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    note TEXT NOT NULL DEFAULT '',
    lines JSONB NOT NULL,
    discrepancy_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT inventory_counts_note_length CHECK (length(note) <= 1000)
);

CREATE INDEX inventory_counts_created_idx ON inventory_counts (created_at DESC, id DESC);

COMMIT;
