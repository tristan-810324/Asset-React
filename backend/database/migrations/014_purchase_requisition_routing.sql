-- Per-item approval policy and stock reservations for purchase requisitions.
BEGIN;

ALTER TABLE item_category_item_names
  ADD COLUMN approval_policy TEXT NOT NULL DEFAULT 'GSO_HEAD',
  ADD COLUMN staff_issue_max_quantity INTEGER,
  ADD COLUMN policy_updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ADD COLUMN policy_updated_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL;

ALTER TABLE item_category_item_names
  ADD CONSTRAINT item_category_item_names_approval_policy_check
    CHECK (approval_policy IN ('GSO_HEAD', 'STAFF_ISSUE')),
  ADD CONSTRAINT item_category_item_names_staff_limit_check
    CHECK (staff_issue_max_quantity IS NULL OR staff_issue_max_quantity > 0),
  ADD CONSTRAINT item_category_item_names_staff_policy_limit_check
    CHECK (approval_policy <> 'STAFF_ISSUE' OR staff_issue_max_quantity IS NOT NULL);

CREATE TABLE item_category_item_name_policy_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_name_id BIGINT NOT NULL REFERENCES item_category_item_names(id) ON DELETE RESTRICT,
  previous_policy TEXT NOT NULL,
  new_policy TEXT NOT NULL,
  previous_staff_limit INTEGER,
  new_staff_limit INTEGER,
  reason TEXT NOT NULL,
  changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT item_category_item_name_policy_history_reason_check CHECK (length(trim(reason)) BETWEEN 1 AND 1000)
);

CREATE INDEX item_category_item_name_policy_history_item_idx
  ON item_category_item_name_policy_history (item_name_id, changed_at DESC, id DESC);

CREATE TABLE purchase_requisition_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES service_requests(id) ON DELETE RESTRICT,
  line_number INTEGER NOT NULL,
  item_name_id BIGINT REFERENCES item_category_item_names(id) ON DELETE SET NULL,
  category TEXT NOT NULL,
  item_name TEXT NOT NULL,
  specifications TEXT NOT NULL DEFAULT '',
  requested_quantity INTEGER NOT NULL,
  approval_policy TEXT NOT NULL DEFAULT 'GSO_HEAD',
  staff_issue_max_quantity INTEGER,
  reserved_quantity INTEGER NOT NULL DEFAULT 0,
  finance_quantity INTEGER NOT NULL DEFAULT 0,
  issued_quantity INTEGER NOT NULL DEFAULT 0,
  route_status TEXT NOT NULL DEFAULT 'WAITING_GSO_HEAD',
  review_note TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT purchase_requisition_lines_request_line_unique UNIQUE (request_id, line_number),
  CONSTRAINT purchase_requisition_lines_quantity_check CHECK (
    requested_quantity > 0 AND reserved_quantity >= 0 AND finance_quantity >= 0
    AND issued_quantity >= 0 AND reserved_quantity + finance_quantity <= requested_quantity
    AND issued_quantity <= reserved_quantity
  ),
  CONSTRAINT purchase_requisition_lines_policy_check CHECK (approval_policy IN ('GSO_HEAD', 'STAFF_ISSUE')),
  CONSTRAINT purchase_requisition_lines_status_check CHECK (route_status IN (
    'WAITING_GSO_HEAD', 'NEEDS_INFORMATION', 'READY_FOR_STAFF', 'PARTIAL_STOCK',
    'WAITING_FINANCE', 'FINANCE_SENT', 'FINANCE_RESPONSE', 'REJECTED',
    'PARTIALLY_ISSUED', 'HANDOVER_PENDING', 'ISSUED', 'CANCELLED'
  ))
);

CREATE INDEX purchase_requisition_lines_route_idx
  ON purchase_requisition_lines (route_status, request_id, line_number);

INSERT INTO purchase_requisition_lines (
  request_id, line_number, item_name_id, category, item_name, specifications,
  requested_quantity, approval_policy, staff_issue_max_quantity, route_status, finance_quantity
)
SELECT request.id,
       requested.ordinality::INTEGER,
       CASE WHEN requested.item->>'itemNameId' ~ '^[0-9]{1,18}$' THEN (requested.item->>'itemNameId')::BIGINT ELSE NULL END,
       COALESCE(requested.item->>'category', 'Others'),
       COALESCE(NULLIF(requested.item->>'itemName', ''), 'General item'),
       COALESCE(requested.item->>'description', ''),
       CASE WHEN requested.item->>'quantity' ~ '^[0-9]{1,6}$' THEN GREATEST(1, (requested.item->>'quantity')::INTEGER) ELSE 1 END,
       COALESCE(saved.approval_policy, 'GSO_HEAD'),
       saved.staff_issue_max_quantity,
       CASE request.status
         WHEN 'Needs Information' THEN 'NEEDS_INFORMATION'
         WHEN 'Approved' THEN 'WAITING_GSO_HEAD'
         WHEN 'Rejected' THEN 'REJECTED'
         WHEN 'GSO Endorsed' THEN 'WAITING_FINANCE'
         WHEN 'Finance Handoff Pending' THEN 'WAITING_FINANCE'
         WHEN 'Finance Handoff Failed' THEN 'WAITING_FINANCE'
         WHEN 'Sent to Finance' THEN 'FINANCE_SENT'
         WHEN 'Finance Response Recorded' THEN 'FINANCE_RESPONSE'
         ELSE 'WAITING_GSO_HEAD'
       END,
       CASE WHEN request.status IN ('GSO Endorsed', 'Finance Handoff Pending', 'Finance Handoff Failed', 'Sent to Finance', 'Finance Response Recorded')
         THEN CASE WHEN requested.item->>'quantity' ~ '^[0-9]{1,6}$' THEN GREATEST(1, (requested.item->>'quantity')::INTEGER) ELSE 1 END ELSE 0 END
  FROM service_requests AS request
 CROSS JOIN LATERAL jsonb_array_elements(COALESCE(request.form_data->'items', '[]'::JSONB)) WITH ORDINALITY AS requested(item, ordinality)
  LEFT JOIN item_category_item_names AS saved
    ON saved.id = CASE WHEN requested.item->>'itemNameId' ~ '^[0-9]{1,18}$' THEN (requested.item->>'itemNameId')::BIGINT ELSE NULL END
 WHERE request.request_type = 'PURCHASE_REQUISITION';

-- Old approvals have no per-line reservations or saved policy snapshot, so ask the Head to
-- review them again instead of showing unreserved stock as ready for issuance.
WITH legacy_approvals AS (
  UPDATE service_requests
     SET status = 'Under Review', updated_at = NOW()
   WHERE request_type = 'PURCHASE_REQUISITION' AND status = 'Approved'
   RETURNING id
)
INSERT INTO service_request_history (request_id, previous_status, new_status, note, changed_by_user_id)
SELECT id, 'Approved', 'Under Review',
       'Reopened during requisition routing update so GSO can verify and reserve stock before issuance.',
       NULL
  FROM legacy_approvals;

CREATE TABLE purchase_requisition_line_allocations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id BIGINT NOT NULL REFERENCES purchase_requisition_lines(id) ON DELETE RESTRICT,
  item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
  quantity INTEGER NOT NULL,
  fulfilled_quantity INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'Reserved',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT purchase_requisition_line_allocations_line_item_unique UNIQUE (line_id, item_id),
  CONSTRAINT purchase_requisition_line_allocations_quantity_check CHECK (
    quantity > 0 AND fulfilled_quantity >= 0 AND fulfilled_quantity <= quantity
  ),
  CONSTRAINT purchase_requisition_line_allocations_status_check CHECK (
    status IN ('Reserved', 'Fulfilled', 'Released')
  )
);

CREATE INDEX purchase_requisition_allocations_item_active_idx
  ON purchase_requisition_line_allocations (item_id, status)
  WHERE status = 'Reserved';

CREATE TABLE purchase_requisition_line_receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id BIGINT NOT NULL REFERENCES purchase_requisition_lines(id) ON DELETE RESTRICT,
  item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  receipt_reference TEXT NOT NULL DEFAULT '',
  received_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  received_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX purchase_requisition_line_receipts_line_idx
  ON purchase_requisition_line_receipts (line_id, received_at DESC, id DESC);

ALTER TABLE employee_issuance_batches
  ADD COLUMN purchase_requisition_id BIGINT REFERENCES service_requests(id) ON DELETE RESTRICT;

ALTER TABLE employee_issuances
  ADD COLUMN purchase_requisition_line_id BIGINT REFERENCES purchase_requisition_lines(id) ON DELETE RESTRICT;

CREATE INDEX employee_issuances_purchase_line_idx
  ON employee_issuances (purchase_requisition_line_id)
  WHERE purchase_requisition_line_id IS NOT NULL;

COMMIT;
