BEGIN;

CREATE TABLE IF NOT EXISTS asset_unit_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_code TEXT NOT NULL UNIQUE,
    item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
    issuance_id BIGINT REFERENCES employee_issuances(id) ON DELETE RESTRICT,
    unit_number INTEGER NOT NULL,
    serial_number TEXT,
    location TEXT NOT NULL DEFAULT '',
    condition TEXT NOT NULL,
    lifecycle_status TEXT NOT NULL DEFAULT 'Active',
    custody_status TEXT NOT NULL DEFAULT 'Available',
    assigned_employee_id BIGINT REFERENCES employees(id) ON DELETE RESTRICT,
    assigned_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    disposal_reason TEXT NOT NULL DEFAULT '',
    disposal_reference TEXT NOT NULL DEFAULT '',
    last_inspected_at TIMESTAMPTZ,
    last_inspected_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    last_inspection_note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT asset_unit_tags_unit_number_positive CHECK (unit_number > 0),
    CONSTRAINT asset_unit_tags_condition_check CHECK (
        condition IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired')
    ),
    CONSTRAINT asset_unit_tags_lifecycle_status_check CHECK (
        lifecycle_status IN ('Active', 'Pending Disposal', 'Disposed')
    ),
    CONSTRAINT asset_unit_tags_custody_status_check CHECK (
        custody_status IN ('Available', 'Issued', 'Borrowed')
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS asset_unit_tags_item_unit_unique_idx
    ON asset_unit_tags (item_id, unit_number);
CREATE UNIQUE INDEX IF NOT EXISTS asset_unit_tags_serial_number_lower_unique_idx
    ON asset_unit_tags (lower(serial_number))
    WHERE serial_number IS NOT NULL AND length(trim(serial_number)) > 0;
CREATE INDEX IF NOT EXISTS asset_unit_tags_issuance_idx
    ON asset_unit_tags (issuance_id, unit_number)
    WHERE issuance_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS asset_unit_tags_employee_custody_idx
    ON asset_unit_tags (assigned_employee_id, custody_status, lifecycle_status);

COMMIT;
