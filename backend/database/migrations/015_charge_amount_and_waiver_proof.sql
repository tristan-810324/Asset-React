-- The amount written on a payment receipt (GSO Staff type it in), and proof for waived charges.
-- A waived charge needs no payment: its proof is the signed waiver form, as a PDF or a picture.
BEGIN;

ALTER TABLE public.charge_receipts
  ADD COLUMN IF NOT EXISTS amount_paid NUMERIC(12, 2) CHECK (amount_paid IS NULL OR (amount_paid > 0 AND amount_paid <= 100000000));

CREATE TABLE IF NOT EXISTS public.charge_waiver_proofs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_kind TEXT NOT NULL CHECK (source_kind IN ('FACILITY', 'RETURN', 'LOSS')),
  source_ref TEXT NOT NULL,
  proof_data TEXT NOT NULL CHECK (length(proof_data) <= 1400000),
  proof_name TEXT NOT NULL DEFAULT '' CHECK (length(proof_name) <= 200),
  proof_mime TEXT NOT NULL CHECK (proof_mime IN ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
  note TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 500),
  uploaded_by_user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  UNIQUE (source_kind, source_ref)
);

COMMIT;
