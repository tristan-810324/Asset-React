BEGIN;

CREATE TABLE IF NOT EXISTS app_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    recipient_role_key TEXT,
    notification_type TEXT NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    href TEXT NOT NULL DEFAULT '',
    dedupe_key TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT app_notifications_recipient_check CHECK (
      (recipient_user_id IS NULL) <> (recipient_role_key IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS app_notifications_user_inbox_idx
    ON app_notifications (recipient_user_id, created_at DESC)
    WHERE resolved_at IS NULL;
CREATE INDEX IF NOT EXISTS app_notifications_role_inbox_idx
    ON app_notifications (recipient_role_key, created_at DESC)
    WHERE resolved_at IS NULL;

COMMIT;
