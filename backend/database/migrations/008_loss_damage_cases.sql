-- Loss & Damage Cases (2026-11-15): GSO Staff decide each Loss / Damage Report. When the requester has to pay,
-- the backend creates a PayMongo TEST payment link. Test mode only: no live key, no real money.
-- The report itself stays in service_requests (request_type LOSS_DAMAGE_REPORT). No existing table is changed.
BEGIN;

-- One decision per report. Only a signed PayMongo webhook can mark it PAID (see paymongo_webhook_events).
CREATE TABLE public.loss_damage_settlements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL,
    resolution text NOT NULL,
    reason text NOT NULL,
    amount_centavos integer,
    currency text DEFAULT 'PHP'::text NOT NULL,
    status text NOT NULL,
    assessed_by_user_id bigint,
    assessed_at timestamp with time zone DEFAULT now() NOT NULL,
    paymongo_link_id text,
    paymongo_checkout_url text,
    paymongo_reference_number text,
    link_created_at timestamp with time zone,
    link_created_by_user_id bigint,
    -- Links GSO cancelled (archived at PayMongo). A payment reported on one of them is logged, never applied.
    previous_link_ids text[] DEFAULT '{}'::text[] NOT NULL,
    paymongo_payment_id text,
    paid_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT loss_damage_settlements_request_key UNIQUE (request_id),
    CONSTRAINT loss_damage_settlements_link_key UNIQUE (paymongo_link_id),
    CONSTRAINT loss_damage_settlements_resolution_check CHECK ((resolution = ANY (ARRAY['NO_CHARGE'::text, 'FOR_REPAIR'::text, 'PAYMENT_REQUIRED'::text]))),
    CONSTRAINT loss_damage_settlements_status_check CHECK ((
        ((resolution = 'NO_CHARGE'::text) AND (status = 'NO_CHARGE'::text))
        OR ((resolution = 'FOR_REPAIR'::text) AND (status = 'FOR_REPAIR'::text))
        OR ((resolution = 'PAYMENT_REQUIRED'::text) AND (status = ANY (ARRAY['PENDING_LINK'::text, 'AWAITING_PAYMENT'::text, 'PAID'::text])))
    )),
    -- PHP 1.00 to PHP 9,999,999.99: the range PayMongo accepts for a payment link.
    CONSTRAINT loss_damage_settlements_amount_check CHECK ((
        ((resolution = 'PAYMENT_REQUIRED'::text) AND (amount_centavos >= 100) AND (amount_centavos <= 999999999))
        OR ((resolution <> 'PAYMENT_REQUIRED'::text) AND (amount_centavos IS NULL))
    )),
    CONSTRAINT loss_damage_settlements_currency_check CHECK ((currency = 'PHP'::text)),
    CONSTRAINT loss_damage_settlements_reason_check CHECK (((length(btrim(reason)) >= 1) AND (length(reason) <= 1000))),
    CONSTRAINT loss_damage_settlements_link_check CHECK (((status <> ALL (ARRAY['AWAITING_PAYMENT'::text, 'PAID'::text])) OR ((paymongo_link_id IS NOT NULL) AND (paymongo_checkout_url IS NOT NULL)))),
    CONSTRAINT loss_damage_settlements_paid_check CHECK (((status = 'PAID'::text) = (paid_at IS NOT NULL))),
    CONSTRAINT loss_damage_settlements_request_id_fkey FOREIGN KEY (request_id) REFERENCES public.service_requests(id) ON DELETE RESTRICT,
    CONSTRAINT loss_damage_settlements_assessed_by_user_id_fkey FOREIGN KEY (assessed_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL,
    CONSTRAINT loss_damage_settlements_link_created_by_user_id_fkey FOREIGN KEY (link_created_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL
);

-- Every PayMongo webhook delivery that passed the signature check, once per PayMongo event id, so a repeated
-- delivery never settles a case twice. Only a hash of the payload is kept, not the payment or personal details.
CREATE TABLE public.paymongo_webhook_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_event_id text NOT NULL,
    event_type text NOT NULL,
    livemode boolean,
    settlement_id bigint,
    paymongo_link_id text,
    payload_sha256 text NOT NULL,
    outcome text NOT NULL,
    received_at timestamp with time zone DEFAULT now() NOT NULL,
    processed_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT paymongo_webhook_events_event_key UNIQUE (provider_event_id),
    CONSTRAINT paymongo_webhook_events_outcome_check CHECK ((outcome = ANY (ARRAY['PROCESSED'::text, 'IGNORED_TYPE'::text, 'REJECTED_LIVE'::text, 'REJECTED_LINK'::text, 'REJECTED_CURRENCY'::text, 'REJECTED_AMOUNT'::text, 'REJECTED_STATE'::text]))),
    CONSTRAINT paymongo_webhook_events_settlement_id_fkey FOREIGN KEY (settlement_id) REFERENCES public.loss_damage_settlements(id) ON DELETE SET NULL
);

CREATE INDEX loss_damage_settlements_status_idx ON public.loss_damage_settlements USING btree (status, request_id);

CREATE INDEX paymongo_webhook_events_settlement_idx ON public.paymongo_webhook_events USING btree (settlement_id, received_at DESC) WHERE (settlement_id IS NOT NULL);

COMMIT;
