-- Departments, positions, the employee master list, and requester verification profiles.
-- Consolidated from the pre-consolidation migrations (archived in migrations_archive/pre-consolidation-2026-11-15).
-- Reference data is included. One-time data conversions are not, because a new database has no rows to convert.
BEGIN;

CREATE TABLE public.departments (
    id bigint NOT NULL,
    name text NOT NULL,
    created_by_user_id bigint,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT departments_name_not_blank CHECK ((length(TRIM(BOTH FROM name)) > 0))
);

CREATE TABLE public.employee_positions (
    id bigint NOT NULL,
    name text NOT NULL,
    created_by_user_id bigint,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT employee_positions_name_not_blank CHECK ((length(TRIM(BOTH FROM name)) > 0))
);

CREATE TABLE public.employees (
    id bigint NOT NULL,
    employee_code text NOT NULL,
    first_name text NOT NULL,
    middle_name text DEFAULT ''::text NOT NULL,
    last_name text NOT NULL,
    suffix text DEFAULT ''::text NOT NULL,
    department text NOT NULL,
    "position" text NOT NULL,
    email text NOT NULL,
    status text DEFAULT 'Active'::text NOT NULL,
    picture_data text,
    created_by_user_id bigint,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT employees_code_not_blank CHECK ((length(TRIM(BOTH FROM employee_code)) > 0)),
    CONSTRAINT employees_department_not_blank CHECK ((length(TRIM(BOTH FROM department)) > 0)),
    CONSTRAINT employees_email_not_blank CHECK ((length(TRIM(BOTH FROM email)) > 0)),
    CONSTRAINT employees_first_name_not_blank CHECK ((length(TRIM(BOTH FROM first_name)) > 0)),
    CONSTRAINT employees_last_name_not_blank CHECK ((length(TRIM(BOTH FROM last_name)) > 0)),
    CONSTRAINT employees_position_not_blank CHECK ((length(TRIM(BOTH FROM "position")) > 0)),
    CONSTRAINT employees_status_check CHECK ((status = ANY (ARRAY['Active'::text, 'Inactive'::text])))
);

CREATE TABLE public.requester_identity_profiles (
    user_id bigint NOT NULL,
    employee_code text NOT NULL,
    first_name text DEFAULT ''::text NOT NULL,
    middle_name text DEFAULT ''::text NOT NULL,
    last_name text DEFAULT ''::text NOT NULL,
    suffix text DEFAULT ''::text NOT NULL,
    department text NOT NULL,
    "position" text NOT NULL,
    contact_number text NOT NULL,
    picture_data text,
    verification_status text DEFAULT 'Pending'::text NOT NULL,
    review_note text DEFAULT ''::text NOT NULL,
    submitted_at timestamp with time zone DEFAULT now() NOT NULL,
    reviewed_at timestamp with time zone,
    reviewed_by_user_id bigint,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT requester_identity_contact_not_blank CHECK ((length(TRIM(BOTH FROM contact_number)) > 0)),
    CONSTRAINT requester_identity_department_not_blank CHECK ((length(TRIM(BOTH FROM department)) > 0)),
    CONSTRAINT requester_identity_employee_code_not_blank CHECK ((length(TRIM(BOTH FROM employee_code)) > 0)),
    CONSTRAINT requester_identity_position_not_blank CHECK ((length(TRIM(BOTH FROM "position")) > 0)),
    CONSTRAINT requester_identity_status_check CHECK ((verification_status = ANY (ARRAY['Pending'::text, 'Verified'::text, 'Needs Correction'::text])))
);

ALTER TABLE public.departments ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.departments_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE public.employee_positions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.employee_positions_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE public.employees ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.employees_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.departments
    ADD CONSTRAINT departments_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.employee_positions
    ADD CONSTRAINT employee_positions_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.employees
    ADD CONSTRAINT employees_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.requester_identity_profiles
    ADD CONSTRAINT requester_identity_profiles_pkey PRIMARY KEY (user_id);

CREATE UNIQUE INDEX departments_name_lower_unique_idx ON public.departments USING btree (lower(name));

CREATE UNIQUE INDEX employee_positions_name_lower_unique_idx ON public.employee_positions USING btree (lower(name));

CREATE UNIQUE INDEX employees_email_lower_unique_idx ON public.employees USING btree (lower(email));

CREATE UNIQUE INDEX employees_employee_code_lower_unique_idx ON public.employees USING btree (lower(employee_code));

CREATE INDEX requester_identity_status_submitted_idx ON public.requester_identity_profiles USING btree (verification_status, submitted_at DESC);

ALTER TABLE ONLY public.departments
    ADD CONSTRAINT departments_created_by_user_id_fkey FOREIGN KEY (created_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL;

ALTER TABLE ONLY public.employee_positions
    ADD CONSTRAINT employee_positions_created_by_user_id_fkey FOREIGN KEY (created_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL;

ALTER TABLE ONLY public.employees
    ADD CONSTRAINT employees_created_by_user_id_fkey FOREIGN KEY (created_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL;

ALTER TABLE ONLY public.requester_identity_profiles
    ADD CONSTRAINT requester_identity_profiles_reviewed_by_user_id_fkey FOREIGN KEY (reviewed_by_user_id) REFERENCES public.users(id) ON DELETE SET NULL;

ALTER TABLE ONLY public.requester_identity_profiles
    ADD CONSTRAINT requester_identity_profiles_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;

