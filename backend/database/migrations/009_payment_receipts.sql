-- Payment receipts for charged items. GSO Staff upload the receipt image and mark the charge Paid.
-- The uploader and the time are kept, so a fake image can be traced to the staff member who uploaded it.
BEGIN;

CREATE TABLE IF NOT EXISTS public.charge_receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_kind TEXT NOT NULL CHECK (source_kind IN ('FACILITY', 'RETURN', 'LOSS')),
  source_ref TEXT NOT NULL,
  receipt_data TEXT NOT NULL CHECK (length(receipt_data) <= 1400000),
  receipt_name TEXT NOT NULL DEFAULT '' CHECK (length(receipt_name) <= 200),
  note TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 500),
  uploaded_by_user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  UNIQUE (source_kind, source_ref)
);

COMMIT;
