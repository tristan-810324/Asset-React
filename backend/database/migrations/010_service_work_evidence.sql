-- Job / service requests: how the job was resolved when work is completed, and photos from the requester and staff.
-- Photos are stored as small compressed images (the screens resize them before upload), in their own table so the
-- request's form data and the list screens stay small.
BEGIN;

ALTER TABLE public.service_work_orders
  ADD COLUMN IF NOT EXISTS resolution_type TEXT CHECK (resolution_type IS NULL OR resolution_type IN ('FIXED', 'REPLACED', 'NOT_FIXED', 'REFERRED'));

CREATE TABLE IF NOT EXISTS public.service_work_order_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES public.service_work_orders(request_id) ON DELETE CASCADE,
  source TEXT NOT NULL CHECK (source IN ('REQUEST', 'REQUESTER_UPDATE', 'STAFF_PROGRESS', 'STAFF_COMPLETION')),
  photo_data TEXT NOT NULL CHECK (photo_data ~ '^data:image/(jpeg|png|webp);base64,' AND length(photo_data) <= 600000),
  added_by_user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS service_work_order_photos_request_idx
  ON public.service_work_order_photos (request_id, created_at);

COMMIT;
