-- One barcode tag per physical unit of individually tracked stock, and the history of retired
-- barcodes. A barcode lasts for one issuance: a reprint or a return retires it, the unit gets a
-- new one, and a copy of an old label stops working.
BEGIN;

CREATE TABLE asset_unit_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_code TEXT NOT NULL UNIQUE,
    item_id BIGINT NOT NULL REFERENCES item_catalog(id) ON DELETE RESTRICT,
    unit_number INTEGER NOT NULL,
    serial_number TEXT,
    location TEXT NOT NULL DEFAULT '',
    condition TEXT NOT NULL,
    lifecycle_status TEXT NOT NULL DEFAULT 'Active',
    custody_status TEXT NOT NULL DEFAULT 'Available',
    issuance_id BIGINT REFERENCES employee_issuances(id) ON DELETE RESTRICT,
    assigned_employee_id BIGINT REFERENCES employees(id) ON DELETE RESTRICT,
    assigned_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    disposal_reason TEXT NOT NULL DEFAULT '',
    disposal_reference TEXT NOT NULL DEFAULT '',
    last_inspected_at TIMESTAMPTZ,
    last_inspected_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    last_inspection_note TEXT NOT NULL DEFAULT '',
    label_version INTEGER NOT NULL DEFAULT 1,
    -- The one print of the current barcode; printing it again needs a reprint.
    label_printed_at TIMESTAMPTZ,
    label_printed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT asset_unit_tags_unit_number_positive CHECK (unit_number > 0),
    CONSTRAINT asset_unit_tags_condition_check CHECK (
        condition IN ('New', 'Good', 'Fair', 'Needs Repair', 'Under Maintenance', 'Unserviceable', 'Retired')
    ),
    CONSTRAINT asset_unit_tags_lifecycle_status_check CHECK (
        lifecycle_status IN ('Active', 'Pending Disposal', 'Disposed')
    ),
    CONSTRAINT asset_unit_tags_custody_status_check CHECK (
        custody_status IN ('Available', 'Issued', 'Borrowed')
    )
);

CREATE UNIQUE INDEX asset_unit_tags_item_unit_unique_idx ON asset_unit_tags (item_id, unit_number);
CREATE UNIQUE INDEX asset_unit_tags_serial_number_lower_unique_idx
    ON asset_unit_tags (lower(serial_number))
    WHERE serial_number IS NOT NULL AND length(trim(serial_number)) > 0;
CREATE INDEX asset_unit_tags_issuance_idx
    ON asset_unit_tags (issuance_id, unit_number)
    WHERE issuance_id IS NOT NULL;
CREATE INDEX asset_unit_tags_employee_custody_idx
    ON asset_unit_tags (assigned_employee_id, custody_status, lifecycle_status);

-- Every retired barcode, who retired it, and why.
CREATE TABLE asset_label_reprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_unit_tag_id BIGINT NOT NULL REFERENCES asset_unit_tags(id) ON DELETE RESTRICT,
    old_tag_code TEXT NOT NULL,
    new_tag_code TEXT NOT NULL,
    label_version INTEGER NOT NULL,
    kind TEXT NOT NULL DEFAULT 'reprint',
    reason TEXT NOT NULL,
    printed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT asset_label_reprints_kind_check CHECK (kind IN ('reprint', 'return')),
    CONSTRAINT asset_label_reprints_reason_check CHECK (length(btrim(reason)) BETWEEN 1 AND 500)
);

-- A retired code is never reused, and scanning it finds what replaced it.
CREATE UNIQUE INDEX asset_label_reprints_old_code_idx ON asset_label_reprints (old_tag_code);
CREATE INDEX asset_label_reprints_tag_idx ON asset_label_reprints (asset_unit_tag_id, created_at DESC, id DESC);

COMMIT;
