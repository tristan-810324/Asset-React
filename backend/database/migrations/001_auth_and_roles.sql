-- Accounts, roles, and sign-in security: one-time tokens, login history, and rate limits.
BEGIN;

CREATE TABLE roles (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_key TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT roles_role_key_format CHECK (role_key ~ '^[A-Z][A-Z0-9_]{1,39}$')
);

CREATE TABLE permissions (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_key TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE role_permissions (
    role_id SMALLINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    permission_id SMALLINT NOT NULL REFERENCES permissions(id) ON DELETE RESTRICT,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    position TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified_at TIMESTAMPTZ,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT users_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT users_email_not_blank CHECK (length(trim(email)) > 0),
    CONSTRAINT users_token_version_nonnegative CHECK (token_version >= 0)
);

CREATE UNIQUE INDEX users_email_lower_unique_idx ON users (lower(email));

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    role_id SMALLINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, role_id)
);

-- Password reset and email verification codes, stored only as hashes.
CREATE TABLE auth_tokens (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    purpose TEXT NOT NULL,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    attempts SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT auth_tokens_purpose_check CHECK (purpose IN ('reset_otp', 'password_reset', 'email_verification_otp')),
    CONSTRAINT auth_tokens_attempts_check CHECK (attempts >= 0 AND attempts <= 5)
);

CREATE INDEX auth_tokens_user_purpose_created_idx ON auth_tokens (user_id, purpose, created_at DESC);
CREATE INDEX auth_tokens_expiry_idx ON auth_tokens (expires_at);

CREATE TABLE login_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    email TEXT NOT NULL,
    ip_address INET,
    event_type TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT login_events_type_check CHECK (event_type IN ('login_failed', 'login_succeeded'))
);

CREATE INDEX login_events_email_type_time_idx ON login_events (email, event_type, occurred_at DESC);
CREATE INDEX login_events_ip_type_time_idx ON login_events (ip_address, event_type, occurred_at DESC);

CREATE TABLE auth_rate_limits (
    bucket_key TEXT PRIMARY KEY,
    window_started_at TIMESTAMPTZ NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT auth_rate_limits_count_nonnegative CHECK (request_count >= 0)
);

CREATE INDEX auth_rate_limits_updated_idx ON auth_rate_limits (updated_at);

